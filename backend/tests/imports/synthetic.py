def build() -> bytes:
    wb = Workbook()
    wb.remove(wb.active)
    cached: dict[str, dict[str, Decimal]] = {}
    last_g_cell: dict[str, str] = {}
    for code, sheet, title, rows in SHEETS:
        ws = wb.create_sheet(sheet)
        cache = cached.setdefault(sheet, {})
        ws["A1"] = f"الباب :  الثاني      البند : {code.replace('/', ' / ')} {title}"
        ws["H1"] = "نموذج رقم : 23 /6"
        for r in range(2, 6):
            ws[f"A{r}"] = "المبلغ : (  ) د.ل    تفويض رقم : (   )"
        ws["A6"] = "قطاع : ــــ"
        ws["B6"] = "مراقبة الخدمات المالية الواحات(2023م)" if code != "2/21" else "مراقبة الخدمات المالية الواحات 2023"
        for col, label in zip("ABCDEFGHI", ["التاريخ ", "البيان", "رقم المستند", "المبلغ", "جملة المصروفات ",
                                           "الارتباطات القائمة", "جملة المصروفات ", "رصيد البند", "ملاحظات"],
                              strict=True):
            ws[f"{col}7"] = label
        ws["E8"], ws["G8"] = "الفعلية", "الفعلية والأرتباطات"
        for col in "DEFGH":
            ws[f"{col}9"] = "درهم دينار"
        data = rows or [(None, None, 0, 0, None)] * 6
        g_prev = h_prev = Decimal(0)
        for i, (desc, doc, d, e, note) in enumerate(data):
            r = 10 + i
            d, e = Decimal(str(d)), Decimal(str(e))
            ws[f"B{r}"], ws[f"C{r}"], ws[f"D{r}"], ws[f"E{r}"], ws[f"F{r}"] = desc, doc, d, e, 0
            if note:
                ws[f"I{r}"] = note
            quirk = code in ("2/16", "2/18") and desc and desc.startswith("تفويض مالي")
            if quirk:                              # DQ-01/DQ-02: صفر يدوي مكان المعادلة
                ws[f"G{r}"] = 0
                g = Decimal(0)
                if code == "2/16":
                    ws[f"H{r}"] = f"=D{r}-G{r}"
                    h = d - g
                else:
                    ws[f"H{r}"] = f"=(D{r - 1}+D{r})"
                    h = Decimal(str(data[i - 1][2])) + d
            else:
                ws[f"G{r}"] = f"=E{r}+F{r}" + (f"+G{r - 1}" if i else "")
                ws[f"H{r}"] = f"=D{r}-E{r}" if i == 0 else f"=(D{r}+H{r - 1})-E{r}"
                g, h = e + (g_prev if i else 0), (d - e) if i == 0 else (d + h_prev - e)
            cache[f"G{r}"], cache[f"H{r}"] = g, h
            g_prev, h_prev = g, h
        last_g_cell[code] = f"G{10 + len(data) - 1}"
    ws = wb.create_sheet("اجمالى الباب الثانى")
    cache = cached.setdefault(ws.title, {})
    ws["B4"], ws["E4"], ws["F4"] = "الباب الثاني", "الرصيد عن 2023", "الرصيد المتبقي"
    total = Decimal(0)
    for i, (code, sheet, title, _) in enumerate(SHEETS):
        r = 5 + i
        ws[f"B{r}"], ws[f"C{r}"] = 2, int(code.split("/")[1])
        ws[f"D{r}"] = SUMMARY_LABELS.get(code, title)
        ref = f"'{sheet}'!{last_g_cell[code]}"
        ws[f"E{r}"] = f"={ref}"
        cache[f"E{r}"] = cached[sheet][last_g_cell[code]]
        if r <= 32:                               # DQ-03: النطاق لا يشمل الصف 33
            total += cache[f"E{r}"]
    ws["B34"] = "جملة الباب الثاني"
    ws["E34"] = "=SUM(E5:E32)"
    cache["E34"] = total
    buf = io.BytesIO()
    wb.save(buf)
    return _inject_cached_values(buf.getvalue(), wb, cached)


def _inject_cached_values(data: bytes, wb: Workbook, cached: dict[str, dict[str, Decimal]]) -> bytes:
    """يضيف <v> لخلايا المعادلات كما يحفظها Excel (openpyxl لا يكتب القيم المحسوبة)."""
    zin = zipfile.ZipFile(io.BytesIO(data))
    out = io.BytesIO()
    zout = zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED)
    names = {f"xl/worksheets/sheet{i + 1}.xml": ws.title for i, ws in enumerate(wb.worksheets)}
    for item in zin.infolist():
        content = zin.read(item.filename)
        title = names.get(item.filename)
        if title and cached.get(title):
            xml = content.decode("utf-8")
            for ref, val in cached[title].items():
                xml = re.sub(rf'(<c r="{ref}"[^>]*>)(<f>[^<]*</f>)(<v>[^<]*</v>|<v\s*/>)?(</c>)',
                             lambda m, v=val: f"{m.group(1)}{m.group(2)}<v>{v}</v>{m.group(4)}", xml)
            content = xml.encode("utf-8")
        zout.writestr(item, content)
    zout.close()
    return out.getvalue()
